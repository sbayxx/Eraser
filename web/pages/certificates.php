<?php
declare(strict_types=1);
require_once __DIR__ . '/_bootstrap.php';
require_once __DIR__ . '/../includes/pdfreport.php';

$pdo  = db_connect();
$user = web_require_login($pdo);

// ---- Single-certificate PDF download ----
if (isset($_GET['pdf'])) {
    $id = (string)$_GET['pdf'];
    $st = $pdo->prepare('SELECT * FROM certificate WHERE id = ? AND deleted = 0');
    $st->execute([$id]);
    $c = $st->fetch();
    if ($c === false) {
        http_response_code(404);
        echo '<h1>404</h1><p>Certifikat ikke fundet.</p>';
        exit;
    }

    // Prefer the authentic certificate PDF generated by the Boot system and
    // synced up with the results. Fall back to portal-rendered layout only
    // for certificates that were pushed without their PDF.
    if (!empty($c['pdf_bytes'])) {
        $filename = $c['pdf_filename'] ?: ('certifikat_' . preg_replace('/[^A-Za-z0-9_-]/', '_', $c['drive_serial'] ?? $c['id']) . '.pdf');
        http_response_code(200);
        header('Content-Type: application/pdf');
        header('Content-Disposition: attachment; filename="' . $filename . '"');
        header('Content-Length: ' . strlen($c['pdf_bytes']));
        echo $c['pdf_bytes'];
        exit;
    }

    $pdf = new PdfReport();
    $pdf->header('Certifikat for sletning', 'GovernIT Data Eraser - ' . ($c['customer_name'] ?? ''));
    $pdf->section('Oversigt');
    $pdf->field('Kunde', ($c['customer_name'] ?? '') . ' (' . ($c['customer_number'] ?? '') . ')');
    $pdf->field('Projekt', $c['project_name'] ?? '-');
    $pdf->field('Projektnr.', $c['project_number'] ?? '-');
    $pdf->field('Status', $c['status'] ?? '-');
    $pdf->field('Generering', $c['generation_date'] ?? '-');
    $pdf->field('Tekniker', $c['technician_name'] ?? '-');
    $pdf->field('Certifikat-id', $c['id']);
    $pdf->spacer(6);

    $pdf->section('Drev / Computer');
    $pdf->field('Drev', ($c['drive_manufacturer'] ?? '') . ' ' . ($c['drive_model'] ?? ''));
    $pdf->field('Serienr. (drev)', $c['drive_serial'] ?? '-');
    $pdf->field('Serienr. (computer)', $c['computer_serial'] ?? '-');
    $pdf->field('Asset tag', $c['asset_tag'] ?? '-');
    $pdf->field('Drevet størrelse (bytes)', $c['drive_capacity_bytes'] > 0 ? number_format((float)$c['drive_capacity_bytes']) : '-');
    $pdf->spacer(6);

    $pdf->section('Sletning');
    $pdf->field('Profil', $c['profile_name'] ?? '-');
    $pdf->field('Metode', $c['actual_method'] ?? '-');
    $pdf->field('Start', $c['started_at'] ?? '-');
    $pdf->field('Slut', $c['finished_at'] ?? '-');
    $pdf->field('Verifikation', $c['verification_method'] ?? '-');
    $pdf->field('Resultat', $c['verification_result'] ?? '-');
    if (!empty($c['notes'])) {
        $pdf->spacer(4);
        $pdf->field('Noter', mb_substr((string)$c['notes'], 0, 120));
    }

    $pdf->section('Integritet');
    $pdf->paragraph('Dokumentet er genereret af GovernIT Data Eraser Management Portal. ' .
        'Certifikatet er verifikationsbaseret og klassificeret i henhold til den anvendte sletningsprofil.');

    $bytes = $pdf->output();
    $filename = 'certifikat_' . preg_replace('/[^A-Za-z0-9_-]/', '_', $c['drive_serial'] ?? $c['id']) . '.pdf';
    http_response_code(200);
    header('Content-Type: application/pdf');
    header('Content-Disposition: attachment; filename="' . $filename . '"');
    header('Content-Length: ' . strlen($bytes));
    echo $bytes;
    exit;
}

$rows = $pdo->query(
    'SELECT id, certificate_hash, status, customer_name, customer_number, project_name,
            drive_model, drive_serial, technician_name, generation_date
     FROM certificate WHERE deleted=0 ORDER BY generation_date DESC LIMIT 200'
)->fetchAll();

$listRows = '';
foreach ($rows as $r) {
    $tone = $r['status'] === 'PASS' ? 'ok' : 'warn';
    $listRows .= '<tr><td>' . e($r['customer_name'] ?? '') . '</td><td>' . e($r['project_name'] ?? '') . '</td>'
        . '<td>' . e($r['drive_model'] ?? '') . '</td><td>' . e($r['drive_serial'] ?? '') . '</td>'
        . '<td>' . e($r['technician_name'] ?? '') . '</td><td>' . e($r['generation_date'] ?? '') . '</td>'
        . '<td><span class="badge ' . $tone . '">' . e($r['status'] ?? '—') . '</span></td>'
        . '<td class="actions"><a class="btn small" href="/certificates.php?pdf=' . e($r['id']) . '">PDF</a></td></tr>';
}
if ($listRows === '') {
    $listRows = '<tr><td colspan="8" class="muted">Ingen certifikater fundet.</td></tr>';
}

$body = '<div class="toolbar"><span class="muted">' . count($rows) . ' certifikater</span></div>'
    . '<table class="list"><thead><tr><th>Kunde</th><th>Projekt</th><th>Drev</th><th>Serienr.</th><th>Tekniker</th><th>Dato</th><th>Status</th><th></th></tr></thead><tbody>' . $listRows . '</tbody></table>';

render_page($user, 'Certifikater', 'certificates', $body);
